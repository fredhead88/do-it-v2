"""Private dependency copies that preserve npm bin links without escaping."""
import pathlib
import shutil


class UnsafeNodeModules(ValueError):
    pass


def validate(directory):
    directory = pathlib.Path(directory)
    if directory.is_symlink() or not directory.is_dir():
        raise UnsafeNodeModules("unsafe node_modules directory")
    root = directory.resolve()
    try:
        for link in directory.rglob("*"):
            if link.is_symlink():
                # Even an absolute link inside the source would point back to
                # the source after copying, breaking isolation from the cache.
                if link.readlink().is_absolute():
                    raise UnsafeNodeModules("node_modules symlink escapes private tree")
                try:
                    resolved = link.resolve(strict=True)
                except FileNotFoundError:
                    resolved = link.resolve()
                if not resolved.is_relative_to(root):
                    raise UnsafeNodeModules("node_modules symlink escapes private tree")
    except (OSError, RuntimeError):
        raise UnsafeNodeModules("unresolvable node_modules symlink") from None


def copy_tree(source, target):
    """Keep relative links; never dereference or return an escaping tree."""
    target = pathlib.Path(target)
    if target.exists() or target.is_symlink():
        raise UnsafeNodeModules("node_modules target already exists")
    validate(source)
    try:
        shutil.copytree(source, target, symlinks=True)
        validate(target)
    except (UnsafeNodeModules, OSError):
        shutil.rmtree(target, ignore_errors=True)
        raise
